    def _fetch_source(
        self, profile: Any, source_site: str, source_observation_id: int, cancelled: Callable[[], bool],
    ) -> tuple[dict[str, Any], InventoryObservation, HydratedObservation]:
        """Fresh read + hydrate of the source record. Called by BOTH
        ``prepare_preview`` and ``_execute_create``/finalize — never cached
        between them — so the create payload always reflects the source as
        it stands right before the write, per Gate 1E's "no race between
        review and write" discipline."""
        if source_site == "inat":
            auth = self.auth_provider()
            token = auth.api_token if auth.is_authenticated else ""
            if not token:
                raise ObservationCreationError("iNaturalist authentication is required.", "inat_auth_missing")
            raw = _first_result(
                self.inat_client.get_reconciliation_detail(source_observation_id, token, deep=True)
            )
            if not raw or positive_int(raw.get("id")) != source_observation_id:
                raise ObservationCreationError("The iNaturalist source observation is unavailable.", "source_unavailable")
            owner = raw.get("user") if isinstance(raw.get("user"), dict) else {}
            if positive_int(owner.get("id")) != profile.inat_user_id:
                raise ObservationCreationError(
                    "The source observation's owner changed; it is not yours to copy.", "source_owner_changed",
                )
            reader = INatReconciliationReader(self.inat_client)
            inventory = reader.parse_inventory(raw, profile.inat_user_id, None, None)
            from .coordinator import _hydrate_record
            hydrated = _hydrate_record(inventory, raw, authorized=True, include_its=True)
        else:
            mo_raw = _first_result(self.mo_client.observation(source_observation_id, cancelled, detail="high"))
            if not mo_raw or positive_int(mo_raw.get("id")) != source_observation_id:
                raise ObservationCreationError("The Mushroom Observer source observation is unavailable.", "source_unavailable")
            inventory = parse_mo_observation(mo_raw, profile.mo_user_id)
            if inventory.owner_id != profile.mo_user_id:
                raise ObservationCreationError(
                    "The source observation's owner changed; it is not yours to copy.", "source_owner_changed",
                )
            # MO's observation payload's consensus name carries no
            # classification data, so a species-level name still parses as
            # fungi_status='unknown' until resolved via a names() lookup —
            # exactly the enrichment the normal full-scan path already does
            # (coordinator.py's _scan_mo). Missing this step here would make
            # every MO source record fail specimen validation regardless of
            # its actual classification.
            if inventory.fungi_status == "unknown" and inventory.taxon_id is not None:
                from .coordinator import _name_fungi_status, _with_fungi_status
                from .mo_client import results_from_payload
                name_rows = results_from_payload(self.mo_client.names([inventory.taxon_id], cancelled))
                if name_rows:
                    inventory = _with_fungi_status(inventory, _name_fungi_status(name_rows[0]))
            if inventory.fungi_status == "unknown":
                # Smaller issues: fail closed HERE, before any preview or
                # write, rather than letting an unresolved fungal
                # classification proceed all the way through creation and
                # only get caught by pair_finalize's specimen check
                # afterward — by then the remote observation already exists,
                # unconfirmed, for no reason a fresh preview couldn't have
                # caught up front.
                raise ObservationCreationError(
                    "This source observation's fungal classification could not be confirmed; "
                    "refusing to create a missing observation for it.", "fungi_status_unknown",
                )
            from .its import _hydrate_mo_specimen
            hydrated = _hydrate_mo_specimen(inventory, mo_raw)
            raw = mo_raw
        return raw, inventory, hydrated

    def _resolve_inat_taxon(self, name: str) -> tuple[Optional[int], str, Optional[str], str]:
        """Explicitly resolve a Fungi taxon via ``/taxa/autocomplete`` before
        creating. iNat's own create-time ``species_guess`` resolution is a
        SEPARATE, looser algorithm than autocomplete and can silently create
        a taxon-less observation even when autocomplete finds an exact match —
        live-confirmed 2026-07-23: a provisional name ("Calycina sp.
        'citrina-IN01'") that autocomplete resolves exactly still produced
        ``"taxon": null`` via bare ``species_guess``, while passing the same
        ``taxon_id`` explicitly attached it correctly. Never rely on
        create-time free-text guessing alone for a name this matters for.

        Returns ``(taxon_id, resolved_name, gap_note, resolution_mode)``.
        ``gap_note`` is set when the source name itself has no exact iNat
        match but a conservative variant does (MO's group/clade/complex
        ranks, which commonly have no matching iNat taxon) — the gap
        discloses that an approximation was used, per the field-transfer
        policy's "never silently drop or downgrade" rule. ``resolution_mode``
        is one of ``'exact'``, ``'provisional_exact'`` (an exact match on a
        quoted MO provisional name, e.g. "Calycina sp. 'citrina-IN01'"),
        ``'disclosed_rank_approximation'``, or ``''`` (nothing resolved) —
        persisted at journal time (section 5) so finalize can require the
        exact reviewed mode/taxon rather than recomputing a fresh decision.
        """
        cleaned = name.strip()
        if not cleaned:
            return None, "", None, ""

        def _exact_fungi_match(query: str) -> Optional[dict[str, Any]]:
            raw = self.inat_client.get_taxa_autocomplete(query, per_page=5)
            candidates = [r for r in (raw.get("results") or []) if isinstance(r, dict)]
            exact = [
                r for r in candidates
                if str(r.get("name") or "").strip().casefold() == query.casefold()
                and str(r.get("iconic_taxon_name") or "").casefold() == "fungi"
                # "Exact active fungal matches are preferred" (section 10): a
                # matching but inactive/synonym taxon is excluded rather than
                # silently attached — is_active defaults True when the field
                # is absent (older/mocked payloads), never False-by-omission.
                and r.get("is_active", True) is not False
                # A kingdom-rank match (i.e. the source name resolved to
                # "Fungi" itself) is never an acceptable creation taxon here:
                # section 10 requires a source identified only as kingdom
                # Fungi to stay BLOCKED rather than silently create a
                # coarse-taxon observation.
                and str(r.get("rank") or "").casefold() != "kingdom"
            ]
            return exact[0] if len(exact) == 1 else None

        match = _exact_fungi_match(cleaned)
        if match:
            mode = "provisional_exact" if "'" in cleaned or '"' in cleaned else "exact"
            return int(match["id"]), cleaned, None, mode

        # MO's group/clade/complex ranks (species complexes) commonly have no
        # 1:1 iNat taxon. Try the name with that suffix stripped and use the
        # base taxon as an explicitly-disclosed approximation — never silent.
        for suffix in (" group", " clade", " complex"):
            if cleaned.casefold().endswith(suffix):
                base = cleaned[: -len(suffix)].strip()
                base_match = _exact_fungi_match(base)
                if base_match:
                    return (
                        int(base_match["id"]), base,
                        f"Mushroom Observer's '{cleaned}' has no matching iNaturalist taxon "
                        f"(a species-complex rank iNat does not model the same way); approximated "
                        f"as its base taxon '{base}' (iNaturalist taxon id {base_match['id']}).",
                        "disclosed_rank_approximation",
                    )
                break
        return (
            None, cleaned,
            f"Could not confidently resolve a single matching iNaturalist Fungi taxon for "
            f"'{cleaned}'; sent as free text only, and iNaturalist may create the observation "
            f"with no identified taxon at all.",
            "",
        )

    def _derive_creation_fields(
        self, source_site: str, destination_site: str,
        raw: dict[str, Any], inventory: InventoryObservation, hydrated: HydratedObservation,
    ) -> dict[str, Any]:
        """The M2 field-transfer policy matrix (module docstring) turned into
        concrete values. Shared by the preview and the actual write so they
        can never diverge."""
        approved_field_gaps: list[str] = []
        # Free-text disclosures that don't correspond to a specific untransferred
        # field (unlike approved_field_gaps, which is a fixed set of codes
        # tolerated by _execute_pair_finalize's exact-match check) — the taxon
        # resolution note is informational, not a structural gap.
        taxon_warnings: list[str] = []
        observed_on_string = inventory.observed_on.isoformat() if inventory.observed_on else ""
        if not observed_on_string:
            approved_field_gaps.append("observed_date")
        place_guess = inventory.public_locality
        description = hydrated.description

        taxon_id: Optional[int] = None
        resolved_taxon_name = ""
        resolution_mode = ""
        if destination_site == "inat" and inventory.taxon_name:
            taxon_id, resolved_taxon_name, gap_note, resolution_mode = self._resolve_inat_taxon(inventory.taxon_name)
            if gap_note:
                taxon_warnings.append(gap_note)
            if taxon_id is None:
                # Nothing resolved: never let a bare, unconfirmed source
                # string stand in for "the destination taxon" (section 10).
                resolved_taxon_name = ""

        latitude = longitude = None
        positional_accuracy = None
        geoprivacy = ""
        gps_hidden = False
        if hydrated.coordinates_available:
            if destination_site == "inat":
                source_gps_hidden = bool(raw.get("gps_hidden")) if source_site == "mo" else False
                if source_gps_hidden:
                    approved_field_gaps.append("coordinates_hidden_on_source")
                else:
                    latitude, longitude = hydrated.latitude, hydrated.longitude
                    positional_accuracy = hydrated.accuracy_m
                    geoprivacy = "open"
            else:
                latitude, longitude = hydrated.latitude, hydrated.longitude
                positional_accuracy = hydrated.accuracy_m
                source_geoprivacy = str(raw.get("geoprivacy") or "open") if source_site == "inat" else "open"
                gps_hidden = source_geoprivacy != "open"

        if hydrated.specimen_available is not None and destination_site == "inat":
            approved_field_gaps.append("specimen_available")

        taxon_resolution_fingerprint = public_fingerprint(
            "taxon_resolution", inventory.taxon_name, taxon_id, resolved_taxon_name, resolution_mode,
        )
        # Finding 3 (round 3): source_fingerprint only pins the local
        # inventory record's (site, id, unpaired_state, local update
        # timestamp) — it says nothing about whether the actual reviewed
        # date/locality/coordinates/accuracy/description/attribution/gap
        # decisions are still what was approved. A remote change with no
        # corresponding local timestamp bump could otherwise let a fresh
        # reread create with values nobody reviewed. One-way hash only —
        # never stores raw notes or coordinates.
        payload_fingerprint = public_fingerprint(
            "creation_payload", observed_on_string, place_guess, description,
            latitude, longitude, positional_accuracy, geoprivacy,
            ",".join(sorted(approved_field_gaps)), hydrated.attribution_name,
        )
        return {
            "observed_on_string": observed_on_string, "taxon_name": inventory.taxon_name,
            "taxon_rank": inventory.taxon_rank,
            "taxon_id": taxon_id, "resolved_taxon_name": resolved_taxon_name,
            "resolution_mode": resolution_mode,
            "taxon_resolution_fingerprint": taxon_resolution_fingerprint,
            "reviewed_payload_fingerprint": payload_fingerprint,
            "place_guess": place_guess, "description": description,
            "latitude": latitude, "longitude": longitude, "positional_accuracy": positional_accuracy,
            "geoprivacy": geoprivacy, "gps_hidden": gps_hidden,
            "approved_field_gaps": approved_field_gaps, "taxon_warnings": taxon_warnings,
        }

    def prepare_preview(
        self, profile_id: int, source_site: str, source_observation_id: int,
        cancelled: Callable[[], bool] = lambda: False,
    ) -> ObservationCreationPreview:
        if source_site not in {"mo", "inat"}:
            raise ObservationCreationError("Invalid source site.", "invalid_site")
        destination_site = "mo" if source_site == "inat" else "inat"
        if destination_site == "mo":
            # Section 4: only MO->iNaturalist creation has been independently
            # proven to the same safety standard (create endpoint shape,
            # recovery marker search, unknown-outcome lookup, duplicate
            # prevention, taxon mapping, privacy mapping, photo/sequence
            # policy, final verification). iNaturalist->MO creation has none
            # of that proven, so it is fail-closed here, at the earliest
            # possible point, independent of whatever the UI already blocks.
            raise ObservationCreationError(
                "Creating a missing observation on Mushroom Observer from an iNaturalist source is "
                "not supported yet. Only Mushroom Observer -> iNaturalist creation has been proven.",
                "unsupported_creation_direction",
            )
        profile = self.db.profile(profile_id)
        record = self.db.record_detail(profile_id, source_site, source_observation_id)
        if not record:
            raise ObservationCreationError("The source record is unavailable.", "record_unavailable")
        expected_state = "confirmed_missing_on_mo" if destination_site == "mo" else "confirmed_missing_on_inat"
        if str(record.get("unpaired_state")) != expected_state:
            raise ObservationCreationError(
                "This record has not been explicitly confirmed missing on the destination site. "
                "An unpaired record is not automatically a missing record.",
                "not_confirmed_missing",
            )
        auth_generation = self.auth_generation_provider()
        mo_key_generation = self.mo_key_generation_provider()

        raw, inventory, hydrated = self._fetch_source(profile, source_site, source_observation_id, cancelled)
        warnings: list[str] = []
        self._search_for_existing_match(profile, destination_site, inventory, cancelled)

        fields = self._derive_creation_fields(source_site, destination_site, raw, inventory, hydrated)
        if fields["taxon_id"] is None:
            # Section 6: an unresolved destination taxon is never an
            # acceptable "cannot be transferred" gap — creating a taxon-less
            # observation and then refusing to finalize it would leave a
            # permanent incomplete remote record. Block creation entirely,
            # before any write, rather than let the user proceed with no
            # identified taxon.
            reason = "; ".join(fields["taxon_warnings"]) or (
                "The source observation has no taxon/name to resolve."
            )
            raise ObservationCreationError(
                f"No acceptable iNaturalist Fungi taxon could be resolved for this source "
                f"observation, so a missing observation cannot be created for it: {reason}",
                "taxon_unresolved",
            )
        approved_field_gaps = fields["approved_field_gaps"]
        observed_on_string = fields["observed_on_string"]
        place_guess = fields["place_guess"]
        description = fields["description"]
        latitude, longitude = fields["latitude"], fields["longitude"]
        positional_accuracy = fields["positional_accuracy"]
        geoprivacy = fields["geoprivacy"]
        warnings.extend(fields["taxon_warnings"])

        items: list[ObservationCreationItem] = []
        identifier_count = len(hydrated.voucher_identifiers) + len(hydrated.collection_identifiers)
        if identifier_count:
            # Section 10 finding: 'identifier' items were minted as
            # inat_ofv_add, but LinkRepairService._write's INAT_OFV_ADD
            # branch is HARDCODED to send the MO observation's URL as the
            # field value (its only real purpose is the Gate 1B reciprocal
            # link) -- there is no code path here for writing an arbitrary
            # voucher/collection identifier value. Reusing it for an
            # identifier item would silently write the wrong value (the MO
            # link URL, duplicating the reciprocal link) instead of the
            # actual identifier text. Disabled and disclosed rather than
            # exposed as a selectable action that writes incorrect data.
            warnings.append(
                f"{identifier_count} voucher/collection identifier(s) exist on the source observation "
                "but identifier transfer is not available from this dialog; add them manually on "
                "iNaturalist after creation."
            )
        # ITS/sequence follow-up items have no wired executor in this saga
        # (they would route to LinkRepairService, which cannot construct a
        # LinkActionType from an ITS action_type and would fail every time) —
        # honestly disclosed and left out rather than exposed as a selectable
        # action that cannot safely execute (section 5).
        #
        # Round-8 review finding: this used to be gated on
        # ``hydrated.sequence_hashes``, which is ALWAYS empty for an MO source
        # — only coordinator._hydrate_record (the iNaturalist hydrator)
        # populates that field, while ``its._hydrate_mo_specimen`` never sets
        # it — so the disclosure was unreachable in the only supported
        # direction and an MO observation carrying ITS sequences was silently
        # created without any mention of them. MO exposes sequences only via
        # its separate ``/api2/sequences`` endpoint (they are absent from the
        # observation payload entirely, confirmed live), and this preview
        # deliberately does not read it, so the honest disclosure is
        # unconditional and says exactly that rather than implying a count
        # nothing here actually measured.
        if destination_site == "inat":
            warnings.append(
                "ITS/sequence records are never transferred by this dialog, and this preview does "
                "not read Mushroom Observer's sequence list. If this observation has any sequences, "
                "add them manually on iNaturalist after creation."
            )
        items.extend(self._photo_items(source_site, destination_site, profile, raw, warnings, cancelled))

        marker_in_public_notes = destination_site == "mo"
        if marker_in_public_notes:
            warnings.append(
                "The Mushroom Observer create response cannot be matched back to an id directly "
                "(live-proven), so a short recovery marker will be embedded in the new "
                "observation's public Notes field and is visible to anyone who views it."
            )

        source_fingerprint = public_fingerprint(
            "record", source_site, source_observation_id,
            record.get("unpaired_state"), record.get("remote_updated_at") or record.get("last_seen_at"),
        )
        return ObservationCreationPreview(
            profile_id=profile_id, source_site=RemoteSite(source_site),
            source_observation_id=source_observation_id,
            destination_site=RemoteSite(destination_site),
            auth_generation=auth_generation, mo_key_generation=mo_key_generation,
            source_fingerprint=source_fingerprint,
            destination_account_login=(profile.mo_login if destination_site == "mo" else profile.inat_login),
            observed_on_string=observed_on_string, taxon_name=inventory.taxon_name,
            taxon_rank=inventory.taxon_rank,
            taxon_id=fields["taxon_id"], resolved_taxon_name=fields["resolved_taxon_name"],
            resolution_mode=fields["resolution_mode"],
            taxon_resolution_fingerprint=fields["taxon_resolution_fingerprint"],
            reviewed_payload_fingerprint=fields["reviewed_payload_fingerprint"],
            place_guess=place_guess, description=description,
            source_attribution_name=hydrated.attribution_name,
            latitude=latitude, longitude=longitude, positional_accuracy=positional_accuracy,
            geoprivacy=geoprivacy, approved_field_gaps=tuple(approved_field_gaps),
            items=tuple(items), marker_in_public_notes=marker_in_public_notes,
            warnings=tuple(warnings),
        )

    def _search_for_existing_match(
        self, profile: Any, destination_site: str, source_inventory: InventoryObservation,
        cancelled: Callable[[], bool],
    ) -> None:
        """Risk-prioritized pre-creation duplicate search (saga-architecture-rules
        rule 8). Reuses ``matching.score_candidate`` (destination-account,
        date, voucher/collection, and authoritative-link evidence are all
        already weighted highest by ``score_evidence``'s family caps — LINK
        65, SPECIMEN 50, BARCODE 50 versus TAXON 10 — so taxon can never be
        the deciding signal here, matching the plan's "scoring signal only"
        requirement). Fails CLOSED: any read/pagination failure blocks
        creation outright.

        Round-4 finding 1: only the ``inat`` destination is reachable
        (``prepare_preview``/``journal_observation_creation_actions`` both
        reject ``destination_site=='mo'`` before this can ever run), and
        that path now runs a LIVE search against the destination account,
        never the last locally cached scan — a record created after the
        last scan, never loaded into the local inventory, or dropped by
        incomplete pagination would otherwise be invisible here. The
        ``mo``-destination branch below is unreached scaffolding only (same
        caveat as the rest of this module's MO-destination code — see the
        module docstring) and is left on the local cache since there is no
        proven MO-destination search primitive to build a live version on.
        """
        if destination_site == "inat":
            self._live_search_inat_destination(profile, source_inventory, cancelled)
            return
        try:
            candidates = self.db.inventory_records(profile.profile_id, destination_site)
        except Exception as exc:  # noqa: BLE001 - fail closed on any read failure
            raise ObservationCreationError(
                f"Could not search the destination site for an existing match; refusing to create "
                f"an observation without a confirmed clean search ({exc}).",
                "duplicate_search_unavailable",
            ) from exc
        # Only records owned by THIS profile's destination account are ever a
        # plausible match for something this profile is about to create.
        destination_account = profile.mo_user_id
        for candidate in candidates:
            if cancelled():
                raise ReconciliationCancelled("Duplicate search cancelled")
            if candidate.account_id != destination_account:
                continue
            pair = score_candidate(source_inventory, candidate, explicit_review=True)
            if pair is not None and pair.score >= 35:
                raise ObservationCreationError(
                    "A possible match already exists on the destination site — re-review the "
                    "candidate search before creating a new observation.",
                    "possible_match_found",
                )

    def _live_search_inat_destination(
        self, profile: Any, source_inventory: InventoryObservation, cancelled: Callable[[], bool],
    ) -> None:
        """Round-5 finding 1: a DEDICATED, purpose-built duplicate search for
        the one reachable creation direction (MO->iNat) — never a reuse of
        ``INatReconciliationReader.inventory_page``, which is Gate 1A's
        public/unauthenticated fungal-inventory scanner and was silently
        unsuitable here for three independent reasons the round-5 review
        caught: it always injects ``taxon_id=47170`` when cursor-paginated
        (excluding a taxon-less or misidentified-outside-Fungi duplicate —
        exactly the case duplicate detection most needs to catch, since
        taxon is supposed to be scoring evidence, never an inclusion
        filter); it calls the deliberately UNAUTHENTICATED public endpoint
        (a hidden/private-coordinate observation the account can see about
        itself would be invisible); and it never receives an ITS/accession
        field id, so identifier/sequence evidence could never match despite
        this method's own prior docstring claiming otherwise.

        Uses ``INatClient.get_creation_duplicate_search`` (authenticated,
        never taxon-filtered) via two strategies: primarily a bounded
        DATE-WINDOW search around the source's own observed date — cheap,
        and covers the overwhelming majority of real duplicates, since a
        specimen's two records are normally logged close in time; if the
        source has no observed date to bound by, falls back to a capped
        full-account cursor scan (same fail-closed discipline, still
        authenticated, still never taxon-filtered). Every candidate is
        parsed with BOTH the "Mushroom Observer URL" reciprocal-link
        binding and the ITS/accession binding resolved, then scored with
        the identical ``score_candidate`` used everywhere else in this
        module — voucher/accession/sequence identifiers, exact media
        identity, and authoritative-link evidence all outweigh date/
        locality/taxon (see ``matching.EvidenceFamily``'s caps), so taxon
        can never be the deciding signal. Every candidate arrives already
        fully hydrated (the deep field set, not a lighter listing followed
        by a second per-item fetch) — there is no separate "hydrate
        plausible candidates" pass because nothing here is under-hydrated
        to begin with. Fails CLOSED: missing authentication, cancellation,
        any read/parse exception, or a window/account too large to
        exhaustively page through all block creation outright rather than
        accept a partial search.
        """
        auth = self.auth_provider()
        token = auth.api_token if auth.is_authenticated else ""
        if not token:
            raise ObservationCreationError(
                "iNaturalist authentication is required to search the destination account for an "
                "existing match; refusing to create without a confirmed clean search.",
                "duplicate_search_unavailable",
            )
        reader = INatReconciliationReader(self.inat_client)

        # Post-review fix (section 1): the MO reciprocal-link field binding
        # is MANDATORY evidence here, not optional. A binding-load failure
        # (DB error) OR a binding that simply does not exist / is not
        # verified must BLOCK creation outright -- never be silently
        # downgraded to "no link evidence below", which would let a
        # candidate that only matches by reciprocal link slip past the
        # search undetected.
        try:
            mo_binding = self.db.field_binding(profile.profile_id, "mo_url")
        except Exception as exc:  # noqa: BLE001 - fail closed: binding load must not silently degrade
            raise ObservationCreationError(
                "Could not load the required Mushroom Observer reciprocal-link field binding for "
                f"this profile; refusing to create without confirmed reciprocal-link evidence ({exc}).",
                "duplicate_search_unavailable",
            ) from exc
        if mo_binding is None or str(mo_binding["verification_state"]) != "verified":
            raise ObservationCreationError(
                "No verified Mushroom Observer reciprocal-link field binding is configured for this "
                "profile; refusing to create without confirmed reciprocal-link evidence in the "
                "duplicate search.",
                "duplicate_search_unavailable",
            )
        mo_field_id = int(mo_binding["field_id"])

        # The ITS/accession binding is genuinely OPTIONAL: unlike the MO
        # link field, nothing else in this app requires it to exist for a
        # profile to be usable, and many profiles will never configure it.
        # A DB read failure still fails closed (it is indistinguishable from
        # "the binding might exist and we can't tell"); an absent binding is
        # safely treated as "no ITS/accession evidence available", which is
        # honestly disclosed here and in the capability note rather than
        # silently assumed complete.
        try:
            its_binding = self.db.field_binding(profile.profile_id, "its")
        except Exception as exc:  # noqa: BLE001 - fail closed on a genuine read failure only
            raise ObservationCreationError(
                f"Could not load the optional ITS/accession field binding for this profile; "
                f"refusing to create without a confirmed search state ({exc}).",
                "duplicate_search_unavailable",
            ) from exc
        its_field_id = int(its_binding["field_id"]) if its_binding else None

        def _score_page(items: Any) -> None:
            # Section 5: a malformed page structure, a non-dict candidate,
            # or a candidate missing its required identity field must BLOCK
            # creation -- never be silently skipped as though the account
            # were still being fully searched.
            if items is None:
                raise ObservationCreationError(
                    "The destination search returned no results field; refusing to create without "
                    "a confirmed complete search.", "duplicate_search_unavailable",
                )
            if not isinstance(items, list):
                raise ObservationCreationError(
                    "The destination search returned an unexpected result shape; refusing to create "
                    "without a confirmed complete search.", "duplicate_search_unavailable",
                )
            for raw in items:
                if not isinstance(raw, dict):
                    raise ObservationCreationError(
                        "The destination search returned a malformed candidate observation; refusing "
                        "to create without a confirmed complete search.", "duplicate_search_unavailable",
                    )
                try:
                    candidate = reader.parse_inventory(raw, profile.inat_user_id, mo_field_id, its_field_id)
                except Exception as exc:  # noqa: BLE001 - a candidate that cannot be parsed safely fails closed
                    raise ObservationCreationError(
                        f"A destination candidate observation could not be parsed safely; refusing to "
                        f"create without a confirmed complete search ({exc}).",
                        "duplicate_search_unavailable",
                    ) from exc
                pair = score_candidate(source_inventory, candidate, explicit_review=True)
                if pair is not None and pair.score >= 35:
                    raise ObservationCreationError(
                        "A possible match already exists on the destination site (found by a live, "
                        "authenticated search of the destination account) — re-review the candidate "
                        "search before creating a new observation.",
                        "possible_match_found",
                    )

        def _validated_page(payload: Any) -> list[dict[str, Any]]:
            if not isinstance(payload, dict):
                raise ObservationCreationError(
                    "The destination search returned an unexpected response shape; refusing to "
                    "create without a confirmed complete search.", "duplicate_search_unavailable",
                )
            items = payload.get("results")
            _score_page(items)
            return items  # type: ignore[return-value]  # validated list[dict] by _score_page above

        def _date_window_search() -> bool:
            """Efficient bounded search around the source's own observed
            date. Returns True once a full, provable pass has completed
            with zero matches. Date is SCORING evidence only (see
            score_candidate/EvidenceFamily) -- this window is a
            performance optimization, never treated as a substitute for
            the unconditional full-account fallback below, so a
            destination counterpart with no date or a date outside this
            window is still guaranteed to be found."""
            if source_inventory.observed_on is None:
                return False
            window = timedelta(days=30)
            d1 = (source_inventory.observed_on - window).isoformat()
            d2 = (source_inventory.observed_on + window).isoformat()
            page = 1
            while True:
                if cancelled():
                    raise ReconciliationCancelled("Duplicate search cancelled")
                payload = self.inat_client.get_creation_duplicate_search(
                    token, user_id=profile.inat_user_id, page=page, d1=d1, d2=d2,
                )
                items = _validated_page(payload)
                # Terminal condition is PROVABLE from the page shape alone
                # (short/empty page) -- never derived from total_results,
                # which may be omitted, wrong, or disagree with the actual
                # page count.
                if not items or len(items) < 200:
                    return True
                page += 1
                if page > 25:  # 5,000 observations within a 60-day window is implausible; fail closed rather than give up silently
                    raise ObservationCreationError(
                        "Too many observations fall within the destination account's date window "
                        "to exhaustively search; refusing to create without a confirmed complete "
                        "search.", "duplicate_search_incomplete",
                    )

        def _full_account_scan() -> None:
            """Section 1, step 3: the unconditional completeness backstop.
            ALWAYS runs when no candidate has been found yet (whether or
            not the date-window search ran/applied), so a destination
            counterpart with no observed date, a date more than 30 days off,
            no taxon, or a misidentification outside Fungi is still
            demonstrably covered -- the date window is scoring-efficiency
            only, never a hard filter that can hide a candidate from this
            method. Cursor-paginated by ascending id, capped, and guarded
            against a repeated/non-advancing cursor."""
            id_above = 0
            pages_scanned = 0
            max_pages = 250  # 200/page: up to 50,000 observations before failing closed
            seen_cursors: set[int] = set()
            while True:
                if cancelled():
                    raise ReconciliationCancelled("Duplicate search cancelled")
                payload = self.inat_client.get_creation_duplicate_search(
                    token, user_id=profile.inat_user_id, page=1, id_above=id_above,
                )
                items = _validated_page(payload)
                pages_scanned += 1
                if not items:
                    return
                ids: list[int] = []
                for item in items:
                    raw_id = item.get("id")
                    if not isinstance(raw_id, int) or raw_id <= 0:
                        raise ObservationCreationError(
                            "A destination candidate observation had no usable numeric id for "
                            "pagination; refusing to create without a confirmed complete search.",
                            "duplicate_search_unavailable",
                        )
                    ids.append(raw_id)
                next_id_above = max(ids)
                if next_id_above <= id_above or next_id_above in seen_cursors:
                    # The cursor failed to advance (repeated page/cursor) --
                    # block rather than loop indefinitely or silently stop
                    # short of a proven full scan.
                    raise ObservationCreationError(
                        "The destination account search pagination did not advance (repeated page or "
                        "cursor); refusing to create without a confirmed complete search.",
                        "duplicate_search_unavailable",
                    )
                seen_cursors.add(next_id_above)
                id_above = next_id_above
                if len(items) < 200:
                    return  # short page: provable terminal condition
                if pages_scanned >= max_pages:
                    raise ObservationCreationError(
                        "The destination account has too many observations to exhaustively "
                        "search live before creating; refusing to create without a confirmed "
                        "complete search.", "duplicate_search_incomplete",
                    )

        try:
            _date_window_search()
            # Section 1: unconditional completeness backstop. Whether or not
            # a date-window search ran (and regardless of it finding nothing
            # to raise on), a full authenticated account scan always runs
            # before creation is allowed to proceed, so date/taxon can never
            # act as a hard inclusion filter over the account.
            _full_account_scan()
        except (ReconciliationCancelled, ObservationCreationError):
            raise
        except Exception as exc:  # noqa: BLE001 - fail closed on any read/pagination failure
            raise ObservationCreationError(
                f"Could not complete a live search of the destination account for an existing "
                f"match; refusing to create an observation without a confirmed clean search "
                f"({exc}).", "duplicate_search_unavailable",
            ) from exc

    def _photo_items(
        self, source_site: str, destination_site: str, profile: Any, raw: dict[str, Any],
        warnings: list[str], cancelled: Callable[[], bool],
    ) -> list[ObservationCreationItem]:
        """Ownership-filtered photo listing for the preview, now also
        running Gate 1E's LICENSE/COPYRIGHT-HOLDER eligibility policy
        (round-4 finding 8): a photo that ``PhotoSyncService._options``
        would refuse is shown disabled here too, with the same reason,
        instead of appearing selectable and only failing after the
        destination observation and pair already exist.

        The DESTINATION-dependent half of Gate 1E's full pipeline
        (already-transferred ledger, digest-vs-destination duplicate
        detection, a complete destination photo scan) genuinely cannot run
        here — there is no destination observation yet for Gate 2A, unlike
        Gate 1E's already-paired photo sync. That half stays deferred to
        ``_mint_item_followups``, which re-proves it at the last point
        before any write; an item accepted here can still be excluded
        there for a destination-dependent reason.

        Only the proven MO->iNat direction (``inat_photo_attach``) is ever
        offered. iNat->MO photo transfer (``mo_photo_attach``) has no working
        executor: ``PhotoSyncService._write`` unconditionally uploads to iNat
        via ``create_observation_photo_v2``, so an MO-destination photo row
        minted here would misdirect the write at iNat instead of Mushroom
        Observer. Section 5: honest omission over an action type that cannot
        safely execute.

        Round-3 finding 4: the visually reviewed image bytes must be pinned
        HERE, at preview time — the point the thumbnail was actually shown
        to and approved by the user — never established later at item-mint
        time (which runs after destination creation/links/finalize, an
        arbitrarily long time after the user looked at the thumbnail). Each
        ELIGIBLE candidate photo is downloaded and fingerprinted now, exactly
        once (a disabled item is never selectable, so its bytes are never
        needed); mint/execute re-downloads and requires an EXACT match
        against this value, never treats a freshly downloaded image as "the
        reviewed one." A photo that fails to download during preview is
        simply excluded (fail closed), not silently offered without a
        reviewed fingerprint.

        Round-8 review finding (safety-critical): the source images MUST come
        from ``MOClient.images_for_observation`` — the same dedicated
        ``GET /api2/images?observation=<id>&detail=high`` read
        ``PhotoSyncService._refresh`` uses — never from the OBSERVATION
        payload. Feeding the observation payload to ``_mo_photo_snapshots``
        was wrong twice over, both confirmed live against MO:

          * ``results_from_payload`` scans its key list in order and reaches
            ``external_links`` BEFORE ``images``, so an observation carrying
            any external link produced "photos" parsed from LINK rows
            (owner_id 0, no URL, no license) and every one of them was then
            dropped by the ownership filter below — a silent, data-dependent
            "this observation has no photos" for a record that has several.
          * MO's observation serializer puts the PRIMARY image in a separate
            ``primary_image`` key and omits it from ``images``, so even
            without any external link the observation's main photo was
            silently missing from the preview (obs 600000: images endpoint
            returns 1842006/7/8; ``obs["images"]`` returns only 1842007/8).

        Reading through the images endpoint also guarantees the license and
        copyright-holder values fingerprinted here are the SAME ones
        ``_execute_population_items`` re-derives at mint time, so
        ``reviewed_metadata_fingerprint`` cannot mismatch merely because two
        different endpoints were consulted.
        """
        items: list[ObservationCreationItem] = []
        if source_site == "mo" and destination_site == "inat":
            from .photo_license import map_mo_license_to_inat, photo_byte_fingerprint
            from .photos import _mo_photo_snapshots
            account_holder = self.photo_service._account_holder(profile.profile_id)  # noqa: SLF001 - deliberate, documented reuse
            mo_observation_id = int(raw.get("id") or 0)
            source_photos = _mo_photo_snapshots(
                self.mo_client.images_for_observation(mo_observation_id, cancelled),
                mo_observation_id,
            )
            for photo in source_photos:
                if photo.owner_id != profile.mo_user_id:
                    continue
                if cancelled():
                    raise ReconciliationCancelled("Creation preview cancelled")
                if not photo.source_url:
                    continue
                # Mirrors PhotoSyncService._options's license/holder checks
                # exactly (photos.py), applied here at preview time instead
                # of only at mint.
                holder = photo.copyright_holder.strip()
                verdict = map_mo_license_to_inat(photo.license_label)
                disabled_reason = ""
                if not verdict.eligible:
                    disabled_reason = (
                        f"The Mushroom Observer license '{photo.license_label or 'none recorded'}' is "
                        "all-rights-reserved or unrecognised. Uploading it under your iNaturalist "
                        "default license would republish it without permission."
                    )
                elif not account_holder:
                    disabled_reason = (
                        "The reconciliation profile has no verified Mushroom Observer login, so this "
                        "image's authorship cannot be confirmed before republishing it under your "
                        "iNaturalist account."
                    )
                elif not holder:
                    disabled_reason = (
                        "This image records no copyright holder, so its authorship cannot be "
                        "confirmed before republishing it under your account."
                    )
                elif holder.casefold() != account_holder.casefold():
                    disabled_reason = (
                        f"This image's recorded copyright holder ({holder!r}) does not match your "
                        f"verified Mushroom Observer login ({account_holder!r})."
                    )
                reviewed_byte_fingerprint = ""
                if not disabled_reason:
                    # Round-8 review finding: go through PhotoSyncService's own
                    # _download, not a bare download_image. It is the single
                    # place MAX_PHOTO_BYTES and the empty-body check live, and
                    # it is what the item's own mint step will use later — a
                    # bare download here both skipped the size cap (pulling an
                    # arbitrarily large original into a worker thread) and
                    # offered an ENABLED item that _execute_population_items
                    # could then only ever fail, after the destination
                    # observation, links and pair already existed.
                    try:
                        image_bytes = self.photo_service._download(photo)  # noqa: SLF001 - deliberate, documented reuse
                    except Exception as exc:  # noqa: BLE001 - PhotoSyncError or transport failure alike: exclude, never offer
                        warnings.append(
                            f"MO photo {photo.photo_id} could not be downloaded for review and is "
                            f"excluded ({exc})."
                        )
                        continue
                    reviewed_byte_fingerprint = photo_byte_fingerprint(image_bytes)
                items.append(ObservationCreationItem(
                    item_type="photo", source_site=RemoteSite.MO, source_identity=photo.photo_id,
                    description=f"MO photo {photo.photo_id} (license {photo.license_label or 'unknown'})",
                    metadata_fingerprint=public_fingerprint(photo.photo_id, photo.license_label, photo.copyright_holder),
                    source_url=photo.source_url, license_label=photo.license_label,
                    copyright_holder=photo.copyright_holder,
                    reviewed_byte_fingerprint=reviewed_byte_fingerprint,
                    enabled=not disabled_reason, disabled_reason=disabled_reason,
                ))
        else:
            from .photos import _inat_photo_snapshots
            photos = _inat_photo_snapshots(raw, int(raw.get("id") or 0))
            if photos:
                warnings.append(
                    f"{len(photos)} iNaturalist photo(s) exist on the source observation but "
                    "transfer to Mushroom Observer is not available from this dialog; add them "
                    "manually on Mushroom Observer after creation."
                )
        return items

