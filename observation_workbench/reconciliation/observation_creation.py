"""Gate 2A: missing-observation creation.

ONLY Mushroom Observer -> iNaturalist is enabled (section 4/12). This module
still ACCEPTS a ``source_site`` parameter and still contains an MO-destination
code path in a few places (``_execute_create``'s ``else`` branch,
``_create_and_locate_mo_observation``, ``_derive_creation_fields``'s
``else`` branches, ``_photo_items``'s MO-destination branch) — none of that
is independently proven (no taxon/name mapping, no privacy mapping, no
iNat->MO photo executor) and none of it is reachable: both
``prepare_preview`` and ``journal_observation_creation_actions`` reject
``destination_site == 'mo'`` (equivalently, ``source_site == 'inat'``)
explicitly, before any of that code can run. Do not remove those two guards
without independently building and proving the reverse direction to the
same standard as MO->iNat below, and do not read the surviving MO-branch
code as evidence that direction is supported.

Creates a brand-new observation on the opposite site only when the user has
explicitly confirmed the record is genuinely missing there
(``sync_records.unpaired_state`` already ``confirmed_missing_on_mo`` /
``confirmed_missing_on_inat`` — see ``ReconciliationDB.set_confirmed_missing``).
An unpaired record is never automatically treated as a missing one.

Architecture (see the ``saga-architecture-rules`` project memory for the full
rationale): ONE ``sync_actions`` row per remote write, never an aggregate
"populate" row. The saga is a dynamically-sized ``action_group_id``:

    ordinal 0        {site}_observation_create           (this module)
    ordinal 1, 2      reciprocal links (existing link-add service)
    ordinal 3         pair_finalize                       (this module)
    ordinal 4..N      inat_photo_attach, MO->iNat only
                      (existing PhotoSyncService, reused unmodified — this
                      is the ONLY population item type actually minted; see
                      the ENABLED item types note below. inat_ofv_add is
                      used only for the ordinal-1/2 reciprocal links above,
                      NEVER for identifier population — that item type is
                      disabled and never generated by prepare_preview.)

Only ordinal 0 is journaled up front (``ReconciliationDB.
journal_observation_creation_actions``): every later row needs the
destination's mo/inat id, which the compound CHECK on ``sync_actions``
requires for every action_type except the three this module owns. The rest
of the saga is minted lazily by ``execute_group`` once ordinal 0 succeeds,
via ``ReconciliationDB.mint_creation_followup_action``/``mint_creation_item_action``
— at that point both ids are real, so the row looks exactly like any other
action of its type and the existing per-type service executes it without
modification.

CORE IDENTITY BEFORE POPULATION (section-4 "Preferred approach"): the
reciprocal links and ``pair_finalize`` run FIRST, immediately after ordinal 0
succeeds — never after the optional population items. ``PhotoSyncService.
_eligible_pair`` hard-requires ``review_state=='confirmed'`` and would reject
every photo item against a still-provisional pair, so optional population
only ever runs once ``pair_finalize`` has promoted the pair. The reciprocal
link-add rows themselves necessarily still run against the provisional pair
(finalize cannot succeed before they exist) — ``LinkRepairService.
_require_current_source`` has an explicit, narrow, documented exemption for
this (a creation-saga group's own ``pair_id``/``issue_id`` columns are always
NULL, so it validates the action row's OWN pair against the creation ledger
instead — see that method).

A genuinely unpaired source record has no ``sync_pairs`` row. As soon as
ordinal 0's destination id is known, ``execute_group`` creates a PROVISIONAL
local pair (``review_state='provisional'``) so the reciprocal-link/specimen
services have something to operate against. A provisional pair is excluded
from every normal dashboard/candidate listing (see the 'unpaired' category
fix and the ``review_state`` audit in ``coordinator.py``/``ui/reconciliation.py``)
and is promoted to ``'confirmed'`` only by this saga's own ``pair_finalize``
step, never by the ordinary candidate-confirmation UI path.

ENABLED item types (section 5 — honest omission over an unsafe placeholder):
only ``identifier`` (-> ``inat_ofv_add``) and MO->iNat ``photo``
(-> ``inat_photo_attach``) are ever minted. ITS/sequence items and iNat->MO
photo items have no wired executor (sequence rows would route to
``LinkRepairService``, which cannot construct a ``LinkActionType`` from an
ITS action_type and always fails; ``PhotoSyncService._write`` unconditionally
uploads to iNat regardless of direction, so an MO-destination photo row would
misdirect the write). ``prepare_preview`` discloses both gaps as warnings
instead of offering a selectable item that cannot safely execute.

CRITICAL asymmetry (docs/gate_2a_capability_note.md, live-proven 2026-07-23):
Mushroom Observer's create response never carries a usable id, even on a
fully successful synchronous create. So an MO destination ALWAYS follows its
create with a ``find_observation_by_marker`` search to discover the id —
this is the normal happy path on MO, not an outcome_unknown fallback. iNat's
create response carries the id directly (the client-supplied ``uuid`` is
proven idempotent), so no follow-up search is needed there.
"""
