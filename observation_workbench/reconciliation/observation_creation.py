def gap_display_text(code: str) -> str:
    """Human-readable text for a field-gap code, for the UI to render.
    Falls back to the raw code if it's ever unrecognised (fail-visible, not
    fail-silent)."""
    return _GAP_TEXT.get(code, code)


class ObservationCreationError(RuntimeError):
    def __init__(self, message: str, code: str = "observation_creation_unavailable") -> None:
        super().__init__(message)
        self.code = code


